#!/usr/bin/env python3
"""Builds page.h from dashboard.html: fonts and logo get inlined as base64,
because the phone has no internet on the Tank-Monitor WiFi.
Run after editing dashboard.html:  python3 build_page.py
"""
import base64
from pathlib import Path

here = Path(__file__).parent
b64 = lambda name: base64.b64encode((here / "assets" / name).read_bytes()).decode()

html = (here / "dashboard.html").read_text()
html = (html.replace("{{SERIF}}", b64("newsreader-400.woff2"))
            .replace("{{SERIF_ITALIC}}", b64("newsreader-400-italic.woff2"))
            .replace("{{LOGO}}", b64("logo.png")))
assert ")rawliteral" not in html and "{{" not in html

(here / "page.h").write_text(
    "// GENERATED by build_page.py from dashboard.html. Edit dashboard.html, not this file.\n"
    "// Fonts: Newsreader (SIL Open Font License, see assets/Newsreader-OFL.txt).\n"
    "#pragma once\n\n"
    'const char PAGE[] PROGMEM = R"rawliteral(' + html + ')rawliteral";\n')
print("page.h:", len(html), "bytes of HTML")
